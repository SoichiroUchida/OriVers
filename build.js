// node build.js  -> orivers.js (UMD, Node + browser + worker) and index.html (single file)
const fs=require('fs'),path=require('path');
const D=__dirname,src=f=>fs.readFileSync(path.join(D,'src',f),'utf8');
const body=[
 '/* ---- Demaine–Ku core: verbatim from core/core.js (lines 5-760) ---- */',src('core_dk.js'),
 src('sat.js'),src('cap.js'),src('layer.js'),src('convex.js'),src('foldin.js'),src('strip.js')].join('\n');
const lib='/* OriVers algorithm library (generated by build.js — edit src/*) */\n'+
 '(function(root){\n"use strict";\n'+body+
 '\nconst OriVers={capStructure,boundaryAssignment,solveFaces,faceSigma,setGeoTol,signedArea,orient,candidates,candidatesConvex,buildLayerModel,satSolve,'+
 'orderMatrix,modelFromP,countViolated,checkOrder,mvFromOrder,maekawa,solveShape,foldIn,foldInCertified,strip:OVStrip,stripMethod:OVStrip.stripMethod,_int:{ovSplit,ovSegInConvex,ovSegInCapsule,ovClip,ovCCW,ovAbsArea,ovCentroid}};\n'+
 'if(typeof module!=="undefined"&&module.exports)module.exports=OriVers;else root.OriVers=OriVers;\n'+
 '})(typeof self!=="undefined"?self:this);\n';
fs.writeFileSync(path.join(D,'orivers.js'),lib);
const tplPath=path.join(D,'src','index.template.html');
if(fs.existsSync(tplPath)){
  const shapes=fs.readdirSync('/home/enda/projects/orivers-paper/shapes').filter(f=>f.endsWith('.json')).sort()
    .map(f=>{const d=JSON.parse(fs.readFileSync(path.join('/home/enda/projects/orivers-paper/shapes',f)));return {name:f.replace('.json',''),T:d.T,holes:d.holes||[]};});
  let html=fs.readFileSync(tplPath,'utf8');
  html=html.replace('/*@@ORIVERS_LIB@@*/',()=>lib.replace(/<\/script/g,'<\\/script'))
           .replace('/*@@SHAPES@@*/',()=>JSON.stringify(shapes));
  fs.writeFileSync(path.join(D,'index.html'),html);
}
console.log('built',lib.length,'bytes');
